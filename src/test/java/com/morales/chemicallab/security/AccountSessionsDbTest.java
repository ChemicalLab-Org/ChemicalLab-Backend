    @Test void loginActuallyWaitsForResetOrDeactivationPostgresLockAndCannotUseOldCredentials() throws Exception {
        for (boolean deactivate : List.of(false, true)) {
            UserAccount user = account(Role.DOCENTE, false);
            var pool = Executors.newFixedThreadPool(2);
            var locked = new CountDownLatch(1);
            var release = new CountDownLatch(1);
            try {
                var writer = pool.submit(() -> tx().executeWithoutResult(status -> {
                    var managed = users().findById(user.getId()).orElseThrow();
                    sessions().lock(managed);
                    locked.countDown();
                    try { if (!release.await(15, TimeUnit.SECONDS)) throw new IllegalStateException("test timeout"); }
                    catch (InterruptedException e) { throw new RuntimeException(e); }
                    if (deactivate) app.getBean(UserManagementService.class).deactivateTeacher(user.getId());
                    else app.getBean(UserManagementService.class).resetTeacherPassword(user.getId(),
                            new com.morales.chemicallab.dto.ResetPasswordRequest("ResetFictitious123", "ResetFictitious123"));
                }));
                assertThat(locked.await(10, TimeUnit.SECONDS)).isTrue();
                var login = pool.submit(() -> request("POST", "/api/auth/login", null, loginBody(user, PASSWORD)));
                // Observe a real waiting PostgreSQL backend, not just a thread start/barrier.
                boolean blocked = false;
                long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(10);
                while (System.nanoTime() < deadline && !blocked) {
                    try (var statement = control.createStatement(); var rows = statement.executeQuery(
                            "select count(*) from pg_stat_activity where datname=current_database() and wait_event_type='Lock' "
                                    + "and query like '%user_accounts%'")) {
                        rows.next(); blocked = rows.getInt(1) > 0;
                    }
                    if (!blocked) Thread.sleep(30);
                }
                assertThat(blocked).as("login blocked on real account row lock").isTrue();
                assertThat(login.isDone()).isFalse();
                release.countDown(); writer.get(15, TimeUnit.SECONDS);
                assertThat(login.get(15, TimeUnit.SECONDS).statusCode()).isEqualTo(401);
                assertThat(app.getBean(AccountSessionRepository.class).findAll().stream()
                        .filter(s -> s.getUser().getId().equals(user.getId())).count()).isZero();
            } finally { release.countDown(); pool.shutdownNow(); }
        }
    }

