    private String login(UserAccount user) throws Exception {
        var response = request("POST", "/api/auth/login", null, loginBody(user, PASSWORD));
        assertThat(response.statusCode()).isEqualTo(200);
        return body(response).get("token").asText();
    }
    private String loginBody(UserAccount user, String password) { return "{\"usernameOrEmail\":\"" + user.getUsername() + "\",\"password\":\"" + password + "\"}"; }
    private HttpResponse<String> request(String method, String path, String token, String payload) throws Exception {
        var builder = HttpRequest.newBuilder(URI.create(origin + path)).timeout(Duration.ofSeconds(20))
                .header("Content-Type", "application/json");
        if (token != null) builder.header("Authorization", "Bearer " + token);
        return http.send(builder.method(method, payload == null ? HttpRequest.BodyPublishers.noBody() : HttpRequest.BodyPublishers.ofString(payload)).build(), HttpResponse.BodyHandlers.ofString());
    }
    private void assertStatus(String method, String path, String token, String payload, int status) throws Exception {
        var response = request(method, path, token, payload);
        assertThat(response.statusCode()).as(method + " " + path + " => " + response.body()).isEqualTo(status);
    }
